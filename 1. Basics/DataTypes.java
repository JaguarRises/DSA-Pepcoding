public class DataTypes {
    public static void main(String[] args) {
        
        int x = 15;
        int y = 10;
        int sum = x + y;
        System.out.println("Sum of " + x + " and " + y +  " is: "  + sum);

        int product = x * y;

        System.out.println("Product of " + x + " and " + y + " is: " + product);

        int exp = (x * y)/(x + y);

        System.out.println(exp);
        
    }

}
